declare(strict_types=1);

namespace Besnovatyj\SearchManticore;

/**
 * Экранирование пользовательского запроса для полнотекстового выражения `MATCH()`.
 *
 * У Manticore два разбора подряд: сначала SQL разбирает строку в кавычках, потом полнотекстовый
 * движок ищет в ней свои операторы. Кавычки, круглые скобки, `|`, `-`, `@`, `~` и подобное —
 * это операторы языка запросов, и пришедшая от посетителя строка не должна в них превращаться.
 *
 * Фасад уже вычистил ввод до букв, цифр и дефисов, так что здесь остаётся один настоящий случай —
 * дефис: в «интернет-магазин» он часть слова, а перед словом это оператор исключения. Незакрытый
 * оператор роняет разбор запроса целиком, поэтому экранируется весь набор служебных символов:
 * ядро обязано быть безопасным и тогда, когда его позовут в обход фасада.
 *
 * SQL-кавычки здесь не ставятся: строка передаётся параметром запроса, и кавычки расставляет
 * драйвер. Здесь только слой полнотекстового синтаксиса.
 */
final class MatchEscaper
{
    /**
     * Служебные символы языка запросов Manticore.
     *
     * Порядок в классе символов важен только для читаемости: обратный слэш стоит первым, чтобы
     * не потеряться среди экранированных скобок.
     */
    private const string PATTERN = '/([\\\\()|\-!@~"&\/^$=<>])/u';

    /**
     * Обезвредить операторы в тексте запроса.
     */
    public function escape(string $text): string
    {
        return (string)preg_replace(self::PATTERN, '\\\\$1', $text);
    }
}
